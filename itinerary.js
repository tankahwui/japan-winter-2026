const itineraryEscape = value => String(value).replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
function renderStayItinerary() {
 const esc = itineraryEscape;
 const category = (label, entries) => `<div><h4>${label}</h4><ul class="stay-venues">${entries.map(p => `<li><a href="${esc(p.url)}" target="_blank" rel="noopener noreferrer">${esc(p.name)} ↗</a><p>${esc(p.note)}</p><a class="stay-directions" href="https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(p.name)}" target="_blank" rel="noopener noreferrer">Find on map ↗</a></li>`).join('')}</ul></div>`;
 document.querySelector('#stay-itinerary').innerHTML = stayItinerary.map((base, i) => `<details class="stay-plan" id="explore-${base.id}" ${i===0?'open':''}><summary><span class="stay-dates">${esc(base.dates)}</span><span>${esc(base.title)}</span></summary><div class="stay-content"><p>${esc(base.intro)}</p><div class="stay-categories">${category('Cafés & tea',base.cafes)}${category('Shopping ideas',base.shopping)}${category('Places of interest',base.sights)}</div><div class="stay-practical"><div><h4>Suggested outings</h4><ul>${base.outings.map(x=>`<li>${esc(x)}</li>`).join('')}</ul></div><div><h4>Practical notes</h4><ul>${base.notes.map(x=>`<li>${esc(x)}</li>`).join('')}</ul></div></div></div></details>`).join('');
 document.querySelectorAll('[data-stay-jump]').forEach(a=>a.addEventListener('click',()=>{document.querySelector(a.getAttribute('href')).open=true;}));
}
renderStayItinerary();
